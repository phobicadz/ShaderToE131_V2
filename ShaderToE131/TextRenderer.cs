namespace ShaderToE131;

/// <summary>
/// Draws text notifications onto the matrix framebuffer using a built-in 5×7 bitmap
/// font (printable ASCII 0x20..0x7E; column-major, bit 0 = top row).
/// Font data from the classic public-domain 5x7 GLCD font
/// (http://sunge.awardspace.com/glcd-sd/node4.html).
/// </summary>
public static class TextRenderer
{
    public const int GlyphWidth = 5;
    public const int GlyphHeight = 7;
    /// <summary>Horizontal advance per character (glyph width + 1px spacing).</summary>
